namespace Vvveb\Plugins\PaypalSmartButtons\System;

class Csp {
    private static ?string $nonce = null;

    public static function nonce(): string {
        if (self::$nonce === null) {
            self::$nonce = base64_encode(random_bytes(16));
        }

        return self::$nonce;
    }
}